package trust

import (
	"crypto/x509"
	"fmt"
)

// PeerMaterial возвращает байты, по которым ядро узнаёт этот сервер, —
// SubjectPublicKeyInfo сертификата.
//
// Именно SPKI, а не сертификат целиком: сервер вправе перевыпустить сертификат
// с тем же ключом (продление срока), и требовать в этом случае нового
// подтверждения от пользователя значило бы приучать его подтверждать смену
// ключа не глядя — ровно то, от чего вся проверка защищает.
//
// И именно SPKI, а не голый ключ: включённый идентификатор алгоритма исключает
// совпадение ключей разных алгоритмов (RFC 6698, HPKP). Материал для привязки
// CredSSP берётся другой функцией — см. SubjectPublicKey и объяснение там,
// почему это два разных значения, а не небрежность.
//
// Ядро считает отпечаток само, тем же способом, что и Fingerprint ниже: от
// материала, который мы прислали. Поэтому то, что увидит пользователь в
// диалоге, совпадает с тем, что мы пишем в журнал.
func PeerMaterial(certDER []byte) ([]byte, error) {
	cert, err := x509.ParseCertificate(certDER)
	if err != nil {
		return nil, fmt.Errorf("trust: сертификат не разбирается: %w", err)
	}
	return cert.RawSubjectPublicKeyInfo, nil
}
